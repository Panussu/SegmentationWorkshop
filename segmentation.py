# ส่วนที่ 5: การคำนวณตัวชี้วัดประสิทธิภาพของ Segmentation
# =============================================================================
# ประกาศฟังก์ชันสำหรับคำนวณตัวชี้วัดจากจำนวนใน Confusion matrix
def metrics(counts):
    # ดึงค่า TN, FP, FN และ TP ตามลำดับออกจาก Dictionary
    tn, fp, fn, tp = (counts[key] for key in ("TN", "FP", "FN", "TP"))
    # ประกาศฟังก์ชันย่อยสำหรับหารค่าอย่างปลอดภัยเมื่อส่วนเป็นศูนย์
    def divide(a, b):
        # คืนผลหารเมื่อส่วนไม่เป็นศูนย์ มิฉะนั้นคืน 0.0
        return a / b if b else 0.0
    # เริ่มสร้าง Dictionary ของตัวชี้วัดทั้งหมด
    return {
        # คำนวณ Accuracy จากจำนวนพิกเซลที่ทำนายถูกหารด้วยพิกเซลทั้งหมด
        "accuracy": divide(tp + tn, tp + tn + fp + fn),
        # คำนวณ Precision จาก TP หารด้วยจำนวนพิกเซลที่ทำนายว่าเป็นวัตถุทั้งหมด
        "precision": divide(tp, tp + fp),
        # คำนวณ Recall จาก TP หารด้วยจำนวนพิกเซลวัตถุจริงทั้งหมด
        "recall": divide(tp, tp + fn),
        # คำนวณ Intersection over Union ของคลาสวัตถุ
        "iou": divide(tp, tp + fp + fn),
        # คำนวณ Dice coefficient ของคลาสวัตถุ
        "dice": divide(2 * tp, 2 * tp + fp + fn),
    # ปิด Dictionary ของตัวชี้วัด
    }
