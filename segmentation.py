# =============================================================================
# ส่วนที่ 1: คำอธิบายโมดูลและไลบรารีที่ใช้
# =============================================================================
# ระบุว่าโมดูลนี้รวมอัลกอริทึมพื้นฐานสำหรับแยกวัตถุจากพื้นหลังด้วยความต่างของสี
"""อัลกอริทึมพื้นฐาน: สีต่างจากขอบภาพมาก -> มีแนวโน้มเป็นวัตถุ."""
# นำเข้า OpenCV สำหรับแปลงระบบสีและประมวลผลภาพด้วย Morphology
import cv2
# นำเข้า NumPy สำหรับคำนวณข้อมูลภาพในรูปแบบอาร์เรย์
import numpy as np


# =============================================================================
# ส่วนที่ 2: การคำนวณคะแนนความเป็นวัตถุจากความแตกต่างของสี
# =============================================================================
# ประกาศฟังก์ชันสำหรับคำนวณคะแนนความเป็นวัตถุ (แอปเปิลสีแดง) จากช่อง a* ของ CIELAB เท่านั้น
def foreground_score(rgb, distance_scale=20.0):
    # อธิบายข้อมูลนำเข้าและผลลัพธ์ของฟังก์ชัน foreground_score
    """รับภาพ RGB คืนคะแนน 0..1 ต่อพิกเซล โดยใช้เฉพาะช่อง a* (แกนเขียว-แดง) ของระบบสี CIELAB เพื่อตรวจจับสีแดง."""
    # แปลงภาพ RGB เป็นระบบสี CIELAB
    # ใน CIELAB: L* คือความสว่าง, a* คือเขียว-แดง (ค่า > 128 คือสีแดง), b* คือน้ำเงิน-เหลือง
    # ตามข้อกำหนด: ไม่ใช้ L* และ b* ใช้เฉพาะช่อง a* ในการตรวจจับสีแดง
    lab = cv2.cvtColor(rgb, cv2.COLOR_RGB2LAB).astype(np.float32)
    a_channel = lab[:, :, 1]
    
    # รวมพิกเซลขอบภาพ 4 ด้านเพื่อหาค่าความแดงเฉลี่ยของพื้นหลัง (bg_a)
    border_a = np.concatenate([a_channel[0], a_channel[-1], a_channel[:, 0], a_channel[:, -1]])
    bg_a = float(np.median(border_a))
    
    # คำนวณความแดงเฉพาะส่วนที่แดงกว่าพื้นหลัง (a_channel - bg_a)
    diff_a = np.maximum(0.0, a_channel - bg_a)
    
    # ปรับสเกลความแดงให้อยู่ในช่วงคะแนนต่อเนื่อง 0 ถึง 1 ด้วยตัวหาร distance_scale
    return diff_a / (diff_a + float(distance_scale))


# =============================================================================
# ส่วนที่ 3: การทำความสะอาด Binary mask ด้วย Morphology
# =============================================================================
# ประกาศฟังก์ชันสำหรับลดจุดรบกวนและเติมช่องว่างขนาดเล็กใน Binary mask
def clean_mask(mask, kernel_size=3):
    # อธิบายลำดับ Morphology และขนาด Kernel ที่ฟังก์ชันใช้
    """Opening ลบจุดเล็ก; Closing เติมช่องว่างเล็ก ด้วย kernel_size (ค่าเริ่มต้น 3x3)."""
    # ตรวจสอบว่า kernel_size เป็นเลขคี่บวก
    if kernel_size < 1 or kernel_size % 2 == 0:
        raise ValueError(f"kernel_size must be an odd positive integer, got {kernel_size}")
    # สร้าง Kernel รูปวงรีขนาด kernel_size x kernel_size สำหรับทำ Morphology
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (kernel_size, kernel_size))
    # แปลง Mask เป็น uint8 แล้วทำ Opening เพื่อลบจุดวัตถุขนาดเล็ก
    opened = cv2.morphologyEx(mask.astype(np.uint8), cv2.MORPH_OPEN, kernel)
    # ทำ Closing เพื่อเติมช่องว่างเล็ก แปลงผลเป็น Boolean และส่งกลับ
    return cv2.morphologyEx(opened, cv2.MORPH_CLOSE, kernel).astype(bool)


