# ส่วนที่ 4: การนับค่า Confusion matrix ระดับพิกเซล
# =============================================================================
# ประกาศฟังก์ชันสำหรับนับค่าใน Confusion matrix ระดับพิกเซล
def confusion_counts(truth, prediction):
    # อธิบายความหมายของคลาสจริงและคลาสพื้นหลังที่ใช้ในการนับ
    """นับผลระดับพิกเซล; 1=สัตว์, 0=พื้นหลัง."""
    # เริ่มสร้าง Dictionary ที่เก็บจำนวน TN, FP, FN และ TP
    return {
        # นับพิกเซลพื้นหลังที่โมเดลทำนายว่าเป็นพื้นหลังอย่างถูกต้อง
        "TN": int(np.sum(~truth & ~prediction)),
        # นับพิกเซลพื้นหลังที่โมเดลทำนายผิดว่าเป็นวัตถุ
        "FP": int(np.sum(~truth & prediction)),
        # นับพิกเซลวัตถุที่โมเดลทำนายผิดว่าเป็นพื้นหลัง
        "FN": int(np.sum(truth & ~prediction)),
        # นับพิกเซลวัตถุที่โมเดลทำนายว่าเป็นวัตถุอย่างถูกต้อง
        "TP": int(np.sum(truth & prediction)),
    # ปิด Dictionary ของจำนวนค่าใน Confusion matrix
    }


