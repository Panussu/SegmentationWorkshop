# นำเข้า unittest สำหรับสร้างและรันชุดทดสอบอัตโนมัติ
import unittest
# นำเข้า NumPy สำหรับสร้างอาร์เรย์ภาพและ Mask ที่ใช้ทดสอบ
import numpy as np
# นำเข้าฟังก์ชันทั้งหมดที่ต้องการตรวจสอบจากโมดูล Segmentation
from segmentation import foreground_score, clean_mask, confusion_counts, metrics


# =============================================================================
# ส่วนที่ 2: ชุดทดสอบการคำนวณคะแนน Morphology และ Metrics
# =============================================================================
# ประกาศคลาสรวมกรณีทดสอบโดยสืบทอดความสามารถจาก unittest.TestCase
class SegmentationTests(unittest.TestCase):

    # -------------------------------------------------------------------------
    # ส่วนที่ 2.1: ทดสอบ Confusion matrix และ IoU
    # -------------------------------------------------------------------------
    # ประกาศกรณีทดสอบการนับ Confusion matrix และการคำนวณ IoU
    def test_known_confusion(self):
        # สร้าง Ground truth ที่มีพื้นหลังสองตำแหน่งและวัตถุสองตำแหน่ง
        truth = np.array([0, 0, 1, 1], dtype=bool)
        # สร้างผลทำนายให้เกิด TN, FP, FN และ TP อย่างละหนึ่งตำแหน่ง
        prediction = np.array([0, 1, 0, 1], dtype=bool)
        # เรียกฟังก์ชันนับค่าของ Confusion matrix
        counts = confusion_counts(truth, prediction)
        # ตรวจสอบว่าฟังก์ชันนับ TN, FP, FN และ TP ได้อย่างละหนึ่ง
        self.assertEqual(counts, dict(TN=1, FP=1, FN=1, TP=1))
        # ตรวจสอบว่า IoU เท่ากับหนึ่งส่วนสามตามสูตร TP หารด้วย TP บวก FP บวก FN
        self.assertAlmostEqual(metrics(counts)["iou"], 1 / 3)

    # -------------------------------------------------------------------------
    # ส่วนที่ 2.2: ทดสอบคะแนนความแตกต่างของสี
    # -------------------------------------------------------------------------
    # ประกาศกรณีทดสอบภาพสีเดียวและวัตถุที่มีสีต่างจากพื้นหลังชัดเจน
    def test_uniform_image_and_contrasting_object(self):
        # สร้างภาพ RGB สีดำขนาด 21 คูณ 21 พิกเซล
        image = np.zeros((21, 21, 3), dtype=np.uint8)
        # ตรวจสอบว่าภาพสีเดียวกับขอบทั้งหมดได้รับคะแนนวัตถุเป็นศูนย์
        self.assertTrue(np.all(foreground_score(image) == 0))
        # สร้างสี่เหลี่ยมสีขาวขนาด 5 คูณ 5 พิกเซลไว้กลางภาพ
        image[8:13, 8:13] = 255
        # คำนวณคะแนนความเป็นวัตถุของภาพที่มีสี่เหลี่ยมสีขาว
        score = foreground_score(image)
        # ตรวจสอบว่าพิกเซลกลางวัตถุมีคะแนนสูงกว่าพิกเซลมุมพื้นหลัง
        self.assertGreater(score[10, 10], score[0, 0])
        # ตรวจสอบว่าคะแนนทุกพิกเซลอยู่ในช่วง 0 ถึง 1
        self.assertTrue(np.all((score >= 0) & (score <= 1)))

    # -------------------------------------------------------------------------
    # ส่วนที่ 2.3: ทดสอบการลบจุดรบกวนด้วย Morphology
    # -------------------------------------------------------------------------
    # ประกาศกรณีทดสอบว่า Morphology ลบจุดรบกวนที่แยกเดี่ยวได้
    def test_morphology_removes_isolated_pixel(self):
        # สร้าง Binary mask พื้นหลังทั้งหมดขนาด 21 คูณ 21 พิกเซล
        mask = np.zeros((21, 21), dtype=bool)
        # สร้างพื้นที่วัตถุหลักเป็นสี่เหลี่ยมขนาด 7 คูณ 7 พิกเซล
        mask[7:14, 7:14] = True
        # เพิ่มจุดวัตถุเดี่ยวที่ตำแหน่งแถว 2 คอลัมน์ 2 เพื่อจำลอง Noise
        mask[2, 2] = True
        # ทำ Morphology เพื่อทำความสะอาด Binary mask
        cleaned = clean_mask(mask)
        # ตรวจสอบว่าจุดรบกวนเดี่ยวถูกลบออกแล้ว
        self.assertFalse(cleaned[2, 2])
        # ตรวจสอบว่าพื้นที่วัตถุหลักตรงกลางยังคงอยู่
        self.assertTrue(cleaned[10, 10])


